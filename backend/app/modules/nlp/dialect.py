    ("محتاج أعرف تفاصيل", "ما هي معلومات"),
    ("عايز أعرف", "ما هي معلومات"),
    ("محتاج أعرف", "ما هي معلومات"),
    ("إزاي أطلع", "ما إجراءات استخراج"),
    ("عايز أطلعها", "أريد استخراج"),
    ("عايز أطلع", "أريد استخراج"),
