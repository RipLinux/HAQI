@router.get("/services")
async def services(
    q: str | None = Query(default=None),
    category: str | None = Query(default=None),
) -> dict:
    filtered = SAMPLE_SERVICES

    if category and category != "\u0627\u0644\u0643\u0644":
        filtered = [s for s in filtered if s["service_category"] == category]

    if q and q.strip():
        needle = q.strip().lower()
        filtered = [
            s
            for s in filtered
            if needle in s["service_name_ar"].lower()
            or needle in s["service_category"].lower()
            or needle in s["authority"].lower()
        ]

    if not SAMPLE_SERVICES:
        raise HTTPException(status_code=501, detail="Government services are not implemented yet")

    return {
        "status": "success",
        "count": len(filtered),
        "services": filtered,
    }


@router.get("/services/{service_slug}")
async def service_details(service_slug: str) -> dict:
    matched = [s for s in SAMPLE_SERVICES if s["service_slug"] == service_slug]
    if not matched:
        raise HTTPException(status_code=404, detail="Service not found")

    return {
        "status": "success",
        "service_slug": service_slug,
        "procedures": matched,
    }
